/**
 * Filesystem helpers shared by the bridge tools.
 *
 * Every path a tool writes is either an explicit user target or a file this
 * plugin already generated, so a conversion never overwrites an unrelated tree by
 * accident.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve, sep } from 'node:path'
import { assertContract, makeContract } from './ir.js'

/** Marker file that identifies a directory this plugin generated into. */
export const GENERATED_MARKER = 'README-BRIDGE.md'

/** Whether a directory exists and already holds entries. */
export function isNonEmptyDirectory(dir) {
  if (!existsSync(dir)) return false
  if (!statSync(dir).isDirectory()) throw new Error(`path exists and is not a directory: ${dir}`)
  return readdirSync(dir).length > 0
}

/** Resolve a user-supplied path against a base directory. */
export function resolvePath(base, candidate) {
  if (typeof candidate !== 'string' || candidate.trim().length === 0) {
    throw new Error('path must be a non-empty string')
  }
  return resolve(base, candidate)
}

/** Read and validate a contract file. */
export function loadContractFile(file) {
  let text
  try {
    text = readFileSync(file, 'utf8')
  } catch (error) {
    throw new Error(`cannot read contract ${file}: ${error.message}`)
  }
  let parsed
  try {
    parsed = JSON.parse(text)
  } catch (error) {
    throw new Error(`contract ${file} is not valid JSON: ${error.message}`)
  }
  return makeContract(assertContract(parsed))
}

/** Write a contract as pretty JSON, creating parent directories. */
export function writeContractFile(file, contract) {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, `${JSON.stringify(contract, undefined, 2)}\n`, 'utf8')
  return file
}

/**
 * Write generated files below `outDir`.
 *
 * @returns the relative paths written.
 */
export function writeFiles(outDir, files) {
  mkdirSync(outDir, { recursive: true })
  const written = []
  for (const file of files) {
    const full = join(outDir, file.path.split('/').join(sep))
    mkdirSync(dirname(full), { recursive: true })
    writeFileSync(full, file.content, 'utf8')
    written.push(file.path)
  }
  return written
}

/**
 * Refuse to write into a directory holding unrelated files.
 *
 * A directory this plugin generated into carries {@link GENERATED_MARKER}, so
 * client sources can be regenerated in place without asking again.
 */
export function assertWritableTarget(outDir, overwrite) {
  if (!isNonEmptyDirectory(outDir) || overwrite === true) return
  if (existsSync(join(outDir, GENERATED_MARKER))) return
  throw new Error(
    `output directory is not empty and was not generated by this plugin: ${outDir}. `
    + 'Choose a new or empty directory, or pass overwrite: true.',
  )
}
